function scaledTimeboxes(timeboxes, totalSeconds) {
  if (!Array.isArray(timeboxes) || timeboxes.length === 0) return [{ label: "完整课堂过程", seconds: totalSeconds }];
  const oldTotal = timeboxes.reduce((sum, item) => sum + item.seconds, 0) || 1;
  const raw = timeboxes.map((item) => (item.seconds * totalSeconds) / oldTotal);
  const floors = raw.map(Math.floor);
  let remainder = totalSeconds - floors.reduce((sum, value) => sum + value, 0);
  const order = raw.map((value, index) => ({ index, fraction: value - floors[index] })).sort((a, b) => b.fraction - a.fraction);
  for (let index = 0; index < remainder; index += 1) floors[order[index % order.length].index] += 1;
  return timeboxes.map((item, index) => ({ label: item.label, seconds: floors[index] }));
}

