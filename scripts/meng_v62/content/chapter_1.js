function page(value) {
  const required = [
    "page_id", "title", "minutes", "literary_object", "current_difficulty",
    "unique_function", "visible", "first_glance", "information_state",
    "student_action", "artifact", "normal_path", "bounded_feedback", "revision",
    "teacher_synthesis", "story_return", "next_use", "deletion_loss", "merge_test",
    "visual_duty", "interaction_signature", "first_person_reception", "script",
  ];
  for (const key of required) {
    if (value[key] === undefined || value[key] === null || value[key] === "") {
      throw new Error(`${value.page_id || "unknown"} missing ${key}`);
    }
  }
  if (!Array.isArray(value.student_action) || value.student_action.length < 1 || value.student_action.length > 3) {
    throw new Error(`${value.page_id} student_action must contain 1-3 actions`);
  }
  for (const key of ["teacher_spoken", "scene", "stage_directions", "timeboxes", "branches", "listener_task", "evidence_location", "cut_line"]) {
    if (!value.script[key] || !value.script[key].length) throw new Error(`${value.page_id} script missing ${key}`);
  }
  return value;
}

